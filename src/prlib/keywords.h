#pragma once

#include <cstddef>
#include <string>
#include <vector>

// Занятые имена движка: то, что интерфейс читает командой
// `prologd --list-keywords` и полем `keywords` события `ready`.
//
// Список живёт в движке, а не в интерфейсе: подсказки и подсветка редактора
// должны знать ровно те имена, которые движок принимает, иначе они разойдутся с
// ним.  Реализация — в functions.cpp, рядом со списком встроенных предикатов
// (NamesOfPredicates) и проверкой арностей (bpred), откуда и берутся данные.
namespace prologd {

// Одно занятое имя.
struct ReservedName {
  //: Имя, как его пишут в программе.
  std::string name;
  //: Арности, которые движок принимает; пусто, если он их не проверяет.
  std::vector<size_t> arities;
  //: Имя принимает любое число аргументов (`ВЫВОД`).
  bool variadic = false;
  //: Имя можно назвать целью; `mod` и `div` — только операторы `#…#`.
  bool callable = true;

  //: Как имя показывают: строка на арность (`СЛУЧ/1`, `СЛУЧ/3`), `ВЫВОД/+` для
  //: имени, у которого арностей нет, или голое имя (`mod`).
  std::vector<std::string> labels() const;
};

//: Занятые имена, упорядоченные по имени (по байтам, как их сравнивает движок).
std::vector<ReservedName> reserved_names();

}  // namespace prologd
